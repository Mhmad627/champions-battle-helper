"""Download Pokémon sprites from PokéAPI's sprite collection and save small WebP icons for the site.

Usage:  python tools/get_sprites.py            (downloads missing sprites into tools/.cache/sprites)
        python tools/get_sprites.py --offline  (only use sprites already in the cache)

Reads data/pokemon.js (run tools/build_data.py first) and writes:
  assets/pokemon/<pokeapiId>.webp   each sprite, cropped to the Pokémon and padded to a square
  data/sprites.js                   window.SPRITES = [ids that have an icon]; others fall back to type icons

Source: https://github.com/PokeAPI/sprites (sprites/pokemon/<id>.png). Needs Pillow.
"""
import hashlib, io, json, os, re, sys, time, urllib.error, urllib.request
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(ROOT, 'tools', '.cache', 'sprites')
OUT = os.path.join(ROOT, 'assets', 'pokemon')
URL = 'https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/{}.png'
SIZE = 64  # output icons are SIZE x SIZE

src = open(os.path.join(ROOT, 'data', 'pokemon.js'), encoding='utf-8').read()
mons = json.loads(src[src.index('['):src.rindex(';')])
ids = sorted({p[6] for p in mons})
os.makedirs(CACHE, exist_ok=True); os.makedirs(OUT, exist_ok=True)


def fetch(pid):
    path = os.path.join(CACHE, f'{pid}.png')
    if os.path.exists(path):
        return path
    if '--offline' in sys.argv:
        # Not cached: keep an icon made on an earlier run rather than dropping it.
        return 'keep' if os.path.exists(os.path.join(OUT, f'{pid}.webp')) else None
    req = urllib.request.Request(URL.format(pid), headers={'User-Agent': 'sprite-icon-builder'})
    err = None
    for attempt in range(3):
        try:
            with urllib.request.urlopen(req, timeout=30) as r:
                data = r.read()
            tmp = path + '.part'                      # write then rename, so a dropped download never
            open(tmp, 'wb').write(data)               # leaves a broken file in the cache
            os.replace(tmp, path)
            return path
        except urllib.error.HTTPError as e:
            if e.code == 404:                         # PokéAPI has no sprite for this form
                return None
            err = e
        except Exception as e:
            err = e
        time.sleep(1 + attempt)
    # Don't quietly drop the icon from data/sprites.js because of a network problem.
    sys.exit(f'Could not download the sprite for {pid} ({err}). data/sprites.js was not updated; run it again.')


have, missing = [], []
for n, pid in enumerate(ids, 1):
    path = fetch(pid)
    if path == 'keep':
        have.append(pid); continue
    if not path:
        missing.append(pid); continue
    try:
        with Image.open(path) as src:                 # 'with' closes the file even if decoding fails,
            im = src.convert('RGBA')                  # so Windows lets us delete a damaged one below
    except Exception:
        im = None
    if im is None:
        os.remove(path)                               # broken cache file: fetch it again next run
        sys.exit(f'The cached sprite for {pid} was damaged and has been deleted. Run the script again.')
    box = im.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox()
    if not box:
        missing.append(pid); continue
    im = im.crop(box)
    side = max(im.size)
    sq = Image.new('RGBA', (side, side), (0, 0, 0, 0))
    sq.paste(im, ((side - im.width) // 2, (side - im.height) // 2))
    # Pixel-art sprites stay crisp when scaled by whole numbers; others are scaled smoothly.
    sq = sq.resize((SIZE, SIZE), Image.NEAREST if SIZE % side == 0 else Image.LANCZOS)
    sq.save(os.path.join(OUT, f'{pid}.webp'), 'WEBP', quality=88, method=6)
    have.append(pid)
    if n % 100 == 0:
        print(f'{n}/{len(ids)}')

# Delete icons for forms that are no longer in data/pokemon.js (or no longer have a sprite).
keep = {f'{i}.webp' for i in have}
for f in os.listdir(OUT):
    if f.endswith('.webp') and f not in keep:
        os.remove(os.path.join(OUT, f))

with open(os.path.join(ROOT, 'data', 'sprites.js'), 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/get_sprites.py. Pokémon (PokéAPI ids) that have an icon in assets/pokemon.\n')
    f.write('window.SPRITES=' + json.dumps(have, separators=(',', ':')) + ';\n')
# Stamp the service worker's icon cache with a fingerprint of the icons, so phones refresh them only when they change.
h = hashlib.sha256()
for i in sorted(have):
    h.update(str(i).encode()); h.update(open(os.path.join(OUT, f'{i}.webp'), 'rb').read())
sw_path = os.path.join(ROOT, 'sw.js')
sw = open(sw_path, encoding='utf-8').read()
sw = re.sub(r"const IMG = 'cbh-icons-[0-9a-f]+';", f"const IMG = 'cbh-icons-{h.hexdigest()[:8]}';", sw)
open(sw_path, 'w', encoding='utf-8', newline='').write(sw)

names = {p[6]: p[0] for p in mons}
print(f'{len(have)} icons, {len(missing)} without a sprite: ' + ', '.join(names[i] for i in missing[:40]))
